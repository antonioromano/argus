  on_arm do
    sha256 "c1c143ca07863619f8a45d6ba8e733569c7f309b4731cfbf79245c9cf80eb58b"
    url "https://github.com/antonioromano/argus/releases/download/v#{version}/Argus-#{version}-arm64.dmg"
  end

  on_intel do
    sha256 "954b2f28f726c0a329c4cb147c3da77ebf45bde59afff8aeceac7b313c5ef3d1"
    url "https://github.com/antonioromano/argus/releases/download/v#{version}/Argus-#{version}.dmg"
  end

  name "Argus"
  desc "Dashboard for managing multiple Claude Code CLI sessions"
  homepage "https://github.com/antonioromano/argus"

  app "Argus.app"

  # App is ad-hoc signed (no Apple Developer cert). Strip the quarantine flag
